<?php

/*
| The agent guideline files (CLAUDE.md, AGENTS.md) are generated by Laravel
| Boost and rewritten by every `boost:install` / `boost:update`, which
| Composer runs on its own after an update. Project rules therefore live in
| `.ai/guidelines/`, which Boost composes into both files — and a file there
| that shares a built-in guideline's name replaces it.
|
| Nothing complains when a regeneration drops one of those rules or stamps
| the wrong PHP version, so these tests do.
*/

$guidelineFiles = ['CLAUDE.md', 'AGENTS.md'];

it('keeps CLAUDE.md and AGENTS.md identical', function () {
    expect(file_get_contents(base_path('AGENTS.md')))
        ->toBe(file_get_contents(base_path('CLAUDE.md')));
});

it('carries the project test rule instead of Boost\'s default', function (string $file) {
    $contents = file_get_contents(base_path($file));

    expect($contents)
        ->toContain('Every change ships with tests in the same change.')
        ->not->toContain('do not require new or updated tests');
})->with($guidelineFiles);

it('carries every project guideline from .ai/guidelines', function (string $file) {
    $contents = str_replace("\r\n", "\n", file_get_contents(base_path($file)));
    $sources = glob(base_path('.ai/guidelines/*')) ?: [];

    expect($sources)->not->toBeEmpty();

    foreach ($sources as $source) {
        $heading = collect(file($source, FILE_IGNORE_NEW_LINES))
            ->first(fn (string $line): bool => str_starts_with($line, '# '));

        expect($heading)->not->toBeNull("{$source} needs a top-level heading");
        expect($contents)->toContain($heading);
    }
})->with($guidelineFiles);

it('stamps the PHP version composer.json requires', function (string $file) {
    $constraint = json_decode(file_get_contents(base_path('composer.json')), true)['require']['php'];

    preg_match('/(\d+\.\d+)/', $constraint, $matches);

    expect(file_get_contents(base_path($file)))
        ->toContain("running on PHP {$matches[1]}");
})->with($guidelineFiles);
